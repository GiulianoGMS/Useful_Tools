BEGIN
  FOR prod IN (SELECT DISTINCT A.SEQPRODUTO, AA.PALETELASTRO, AA.PALETEALTURA, AA.QTDEMBALAGEM FROM NAGT_DEPARA_ADRIANO A INNER JOIN MRL_PRODEMPRESAWM X ON X.SEQPRODUTO = A.SEQPRODUTO
                                                INNER JOIN (SELECT SEQPRODUTO, MAX(E.PALETELASTRO) PALETELASTRO, MAX(E.paletealtura) PALETEALTURA, MAX(E.qtdembalagem) QTDEMBALAGEM
                                                            FROM MLO_PRODESPENDERECO E WHERE E.NROEMPRESA = 507 AND E.especieendereco = 'P' GROUP BY SEQPRODUTO) AA ON AA.SEQPRODUTO = A.SEQPRODUTO
                                 WHERE X.NROEMPRESA = 507 AND NVL(X.PALETELASTRO,0) != NVL(AA.PALETELASTRO,0))
  LOOP
    UPDATE MRL_PRODEMPRESAWM X
      SET X.PALETELASTRO = prod.paletelastro,
          X.PALETEALTURA = prod.paletealtura
      WHERE X.SEQPRODUTO = prod.SEQPRODUTO
        AND X.NROEMPRESA = 507;
  END LOOP;
  END;
